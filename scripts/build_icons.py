"""Regenerate src/calidrux/api/static/icons.js from the Lucide icon set.

Calidrux bundles only the Lucide icons it uses, so the app stays offline.

    npm pack lucide-static            # or download it from https://lucide.dev
    tar xzf lucide-static-*.tgz
    python scripts/build_icons.py package/icons

To add an icon, find its name on https://lucide.dev/icons, add it to NAMES below
and run the script again. Then use it in JavaScript with icon('name'), or in HTML
with <i data-icon="name"></i>.
"""
import re
import sys
from pathlib import Path

NAMES = [
    # sheet index
    "layout-grid", "map", "package-plus", "calendar-clock", "drafting-compass",
    "sliders-horizontal", "chart-column", "arrow-left-right", "route", "boxes",
    "history", "settings",
    # actions
    "search", "plus", "minus", "check", "x", "play", "rotate-cw", "dices", "upload",
    "download", "zoom-in", "zoom-out", "scan", "chevron-left", "chevron-right",
    "arrow-right", "arrow-up", "arrow-down", "corner-down-left", "spline",
    # status
    "snowflake", "thermometer-snowflake", "circle-pause", "circle-check",
    "circle-alert", "triangle-alert", "info",
    # objects
    "package", "map-pin", "warehouse", "chart-pie",
]

OUT = Path(__file__).resolve().parents[1] / "src" / "calidrux" / "api" / "static" / "icons.js"


def inner(svg: str) -> str:
    body = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S).group(1)
    return " ".join(line.strip() for line in body.strip().splitlines())


def main(src: str) -> None:
    src_dir = Path(src)
    entries = []
    for name in NAMES:
        path = src_dir / f"{name}.svg"
        if not path.exists():
            sys.exit(f"Icon not found: {name} (looked in {src_dir})")
        entries.append(f"  '{name}': '{inner(path.read_text())}',")
    OUT.write_text(TEMPLATE.replace("__ENTRIES__", "\n".join(entries)), encoding="utf-8")
    print(f"Wrote {len(NAMES)} icons to {OUT}")


TEMPLATE = """/* Calidrux icons: a subset of Lucide (https://lucide.dev), ISC licence.
   Generated by scripts/build_icons.py. Don't edit the list by hand; add a name to
   NAMES in that script and run it again.

   Use:  icon('snowflake')            -> inline <svg> string for templates
         <i data-icon="search"></i>   -> replaced with the icon when the page loads
   Size and stroke come from --icon-size and --icon-stroke in theme.css. */

const LUCIDE = {
__ENTRIES__
};

function icon(name, cls = '') {
  const body = LUCIDE[name];
  if (!body) { console.warn('Unknown icon:', name); return ''; }
  return `<svg class="i i-${name}${cls ? ' ' + cls : ''}" viewBox="0 0 24 24" fill="none" stroke="currentColor"`
    + ` stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${body}</svg>`;
}

function hydrateIcons(root = document) {
  root.querySelectorAll('i[data-icon]').forEach(el => { el.outerHTML = icon(el.dataset.icon, el.className); });
}

document.addEventListener('DOMContentLoaded', () => hydrateIcons());
"""

if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
